def normalize_index_name(name: str) -> str:
    """MI_INDEX 回傳的名稱可能夾雜全形空白。"""
    return str(name).replace("　", "").replace(" ", "").strip()


def resolve(industry: str, available_index_names: set[str]) -> str | None:
    """回傳該產業對應的類指數名稱；找不到回 None。"""
    mapped = INDUSTRY_TO_INDEX.get(str(industry).strip())
    return mapped if mapped and mapped in available_index_names else None


def tracked_industries() -> list[str]:
    return list(INDUSTRY_TO_INDEX)
